"""Publish synthetic examples from the actual backend, never private inputs.

Run: PYTHONPATH=.:tests/backend .venv/bin/python tests/backend/generate_contracts.py
"""
import json
from pathlib import Path

from fastapi.testclient import TestClient
from conftest import FakeEvidence, decision, fixture_draft
from test_review import FakeEngine, identity
from models import ReviewEngineResult, AnalysisEngineResult
from services.api import create_app
from services.repository import MemoryRepository


class ContractEngine(FakeEngine):
    def analyze(self, scope):
        draft = fixture_draft()
        draft['title'] = 'Regenerated synthetic controls proposal'
        return {"drafts": [draft], "model_metadata": {"provider": "fake", "model": "synthetic-v1"},
                "prompt_metadata": {"version": "synthetic-generation-v1"}}

    def review(self, current, question, turns):
        return dict(super().review(current, question, turns),
                    coverage_gaps=["Synthetic regional field validation remains pending"],
                    model_metadata={"provider": "fake", "model": "synthetic-v1"},
                    prompt_metadata={"version": "synthetic-review-v1"})


def main():
    repository = MemoryRepository()
    draft = fixture_draft()
    app = create_app(repository, FakeEvidence(), engine=ContractEngine({"title": "Reviewed synthetic controls"}))
    with TestClient(app) as client:
        created = app.state.service.create_requirement(draft, "synthetic-contract-run")
        rid = created["id"]
        def get(path):
            response = client.get("/api" + path)
            response.raise_for_status()
            return response.json()
        def post(path, body):
            response = client.post("/api" + path, json=body)
            response.raise_for_status()
            return response.json()
        detail = get(f"/requirements/{rid}")
        thread = post("/review-threads", dict(identity(), entity_kind="requirement", entity_id=rid))
        review_request = dict(identity(), question="Does the source justify the target?")
        started = post(f"/review-threads/{thread['id']}/turns", review_request)
        run = get(f"/analysis-runs/{started['id']}")
        thread_detail = get(f"/review-threads/{thread['id']}")
        approved = post(f"/requirements/{rid}/decisions", decision())
        freeze_request = {"selections": {rid: approved["revision"]}, "expected_ranking_id": repository.read()["rankings"][-1]["id"], "actor_id": "pm-contract", "actor_role": "PM_USER", "rationale": "Reviewed complete synthetic snapshot"}
        frozen = post("/freezes", freeze_request)
        fixture = {
            "fixture_kind": "synthetic_backend_contract",
            "provenance": "Generated by tests/backend/generate_contracts.py from fake providers; no imported BMW evidence.",
            "limitations": ["Synthetic resolver counts, forecasts, strategy and corroboration are not Role 1 lineage proof.", "Example UUIDs and timestamps come from actual API calls; regenerate to refresh."],
            "draft": draft, "resolved_evidence_context": FakeEvidence().resolve(draft),
            "requirement_detail_example": detail,
            "list_example": get("/requirements"), "evidence_example": get(f"/requirements/{rid}/evidence"),
            "history_example": get(f"/requirements/{rid}/history"),
            "decision_request_example": decision(id=rid), "approved_example": approved,
            "review_turn_request_example": review_request, "review_run_example": run,
            "review_thread_example": thread_detail,
            "freeze_request_example": freeze_request, "freeze_example": frozen,
            "export_example": get("/requirements/export"),
            "expected_priority": detail["score"], "expected_evidence": detail["evidence"],
            "change_preview_request_example": {"requirement_id": rid, "expected_revision": approved["revision"], "patch": {"title": "Hypothetical synthetic controls"}},
            "change_preview_example": post("/scoring/preview", {"requirement_id": rid, "expected_revision": approved["revision"], "patch": {"title": "Hypothetical synthetic controls"}}),
            "review_engine_result_schema": ReviewEngineResult.model_json_schema(),
            "analysis_engine_result_schema": AnalysisEngineResult.model_json_schema(),
            "analysis_engine_result_example": ContractEngine().analyze({}),
            "scoring_preview_request_example": {"requirement_id": rid, "weights": {"customer": .5, "reach": .2, "strategy": .2, "ease": .1}},
        }
        analysis_request = {"regions": ["US"], "derivatives": ["G60"], "max_drafts": 1}
        analysis = post('/analysis-runs', analysis_request)
        analysis = get('/analysis-runs/' + analysis['id'])
        proposal_id = analysis['pending_turn_ids'][0]
        proposal = get(f'/requirements/{rid}/proposals/{proposal_id}')
        discard_request = dict(identity(approved['revision']), id=rid)
        fixture.update(analysis_request_example=analysis_request, analysis_run_example=analysis,
                       proposal_list_example=get(f'/requirements/{rid}/proposals'),
                       proposal_example=proposal, proposal_discard_request_example=discard_request,
                       proposal_discard_example=post(f'/requirements/{rid}/proposals/{proposal_id}/discard', discard_request))
    directory = Path(__file__).resolve().parents[2] / "contracts"
    directory.mkdir(exist_ok=True)
    (directory / "fixture_case.json").write_text(json.dumps(fixture, indent=2) + "\n")
    (directory / "openapi.json").write_text(json.dumps(app.openapi(), indent=2) + "\n")


if __name__ == "__main__":
    main()
